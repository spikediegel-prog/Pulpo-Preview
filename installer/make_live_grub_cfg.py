#!/usr/bin/env python3
"""Generate the Pulpo Preview live ISO's GRUB menu from the base ISO's.

The base Ubuntu 24.04 desktop ISO's ``boot/grub/grub.cfg`` is the
source of truth for the kernel lines: the stock config boots with
``linux /casper/vmlinuz --- quiet splash`` (no ``boot=casper`` — the
initramfs auto-detects the live media) and that must not be
"improved" into something untested. This script makes only the
changes the live ISO needs, and fails loudly if the base config does
not look exactly like Ubuntu 24.04.5.1's:

- timeout 30 -> 5
- add gfxterm + the Pulpo boot splash (falls back to text if the
  BMP is missing; boot never depends on the image)
- rename the two entries to Pulpo, live-only (there is NO "Install"
  entry: no disk installer exists in this milestone)
- append ``console=ttyS0 console=tty0`` to the kernel lines so the
  QEMU boot test can capture the kernel log from the serial port
  while it still shows on screen
- add a "Check installer media" entry (casper ``integrity-check``)

Secure Boot: nothing here touches signing. Ubuntu's signed shim/grub
are reused unchanged by the ISO build; no Pulpo key is generated,
enrolled, or used.

Usage: python3 make_live_grub_cfg.py <base-grub.cfg> <out-grub.cfg>
Exit 0 on success, 1 if any expected anchor is missing.
"""

from __future__ import annotations

import sys

HEADER = """\
# Pulpo Preview — UEFI GRUB configuration (live ISO menu)
#
# Generated by installer/make_live_grub_cfg.py from the Ubuntu
# 24.04.5.1 desktop ISO's boot/grub/grub.cfg. The kernel lines are
# the base's, verbatim except for the added serial console.
#
# LIVE ISO ONLY. There is no "Install" entry here on purpose: no disk
# installer exists in this milestone (the partitioner is still open),
# and the menu must not offer one. First boot is a live session that
# autostarts the Control Center; Guided Setup is the button on the
# Control Center System page.
#
# Secure Boot: Ubuntu's signed shim/grub from the base ISO are reused
# unchanged, so the ISO boots under Secure Boot via Microsoft's key.
# No Pulpo key is generated, enrolled, or used for signing — that
# decision is still open.
#
# console=ttyS0 console=tty0: the kernel log also goes to the serial
# port so the QEMU boot test (installer/boot-test.sh) can capture it
# as a file, while still showing on screen. Harmless on hardware
# without a serial port.

"""

GFXTERM_BLOCK = """\
insmod gfxterm
insmod png
insmod jpeg
terminal_output gfxterm
set gfxmode=1920x1080,auto
set gfxpayload=keep

# Boot splash shown while GRUB waits. Falls back to text if the
# background file is missing; boot must never depend on the image.
if [ -f /boot/grub/pulpo-uefi-boot-splash.bmp ]; then
  background_image /boot/grub/pulpo-uefi-boot-splash.bmp
fi

"""

CHECK_MEDIA_ENTRY = """\
menuentry "Check installer media" --class pulpo {
\tset gfxpayload=keep
\tlinux\t/casper/vmlinuz console=ttyS0 console=tty0 integrity-check --- quiet splash
\tinitrd\t/casper/initrd
}
"""

CONSOLE = " console=ttyS0 console=tty0"


def _replace_once(text: str, old: str, new: str, what: str) -> str:
    count = text.count(old)
    if count != 1:
        raise ValueError(f"expected exactly 1 occurrence of {what}, found {count}")
    return text.replace(old, new)


def make_live_grub_cfg(base: str) -> str:
    out = _replace_once(base, "set timeout=30", "set timeout=5", "timeout line")
    out = _replace_once(
        out, "set timeout=5\n", "set timeout=5\nset default=0\n",
        "timeout line for default",
    )
    out = _replace_once(
        out, "loadfont unicode\n", "loadfont unicode\n\n" + GFXTERM_BLOCK,
        "loadfont line",
    )
    out = _replace_once(
        out,
        'menuentry "Try or Install Ubuntu" {',
        'menuentry "Try Pulpo Preview 0.1.0 (live, no install)" --class pulpo {',
        "live menuentry",
    )
    out = _replace_once(
        out,
        'menuentry "Ubuntu (safe graphics)" {',
        'menuentry "Pulpo Preview 0.1.0 (safe graphics)" --class pulpo {',
        "safe-graphics menuentry",
    )
    # Kernel lines: insert the serial console right after the kernel
    # path, keeping the base's own parameters (including the position
    # of `---`) untouched.
    if out.count("\t/casper/vmlinuz") != 2:
        raise ValueError("expected exactly 2 linux lines with /casper/vmlinuz")
    out = out.replace("\t/casper/vmlinuz", "\t/casper/vmlinuz" + CONSOLE)
    out = _replace_once(
        out, "grub_platform\n", CHECK_MEDIA_ENTRY + "grub_platform\n",
        "grub_platform anchor",
    )
    if "Install Pulpo" in out or "Try or Install Ubuntu" in out:
        raise ValueError("an Install entry survived the transform")
    return HEADER + out


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(f"usage: {argv[0]} <base-grub.cfg> <out-grub.cfg>", file=sys.stderr)
        return 2
    base = open(argv[1], encoding="utf-8").read()
    try:
        out = make_live_grub_cfg(base)
    except ValueError as exc:
        print(f"make_live_grub_cfg: {exc}", file=sys.stderr)
        return 1
    open(argv[2], "w", encoding="utf-8").write(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
